"""Markdown report export."""
from __future__ import annotations

from pathlib import Path

from reports.json_exporter import ExportError
from reports.report_data import build_report

ORDER = ["Critical", "High", "Medium", "Low", "Informational"]


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def to_markdown(scan: dict) -> str:
    r = build_report(scan)
    s = r["summary"]["by_severity"]
    out = [f"# CyberScope Security Assessment Report", "",
           f"**Target:** {r['target']}  ", f"**Scan ID:** {r['scan_id']}  ",
           f"**Date (UTC):** {r['scan_timestamp']}  ", f"**Status:** {r['scan_status']}  ",
           f"**Generated by:** CyberScope v{r['application_version']}", "", "## Executive Summary", ""]
    notable = s.get("Critical", 0) + s.get("High", 0) + s.get("Medium", 0) + s.get("Low", 0)
    out.append(f"CyberScope ran safe, non-destructive checks against **{r['hostname']}** and recorded "
               f"**{r['summary']['total_findings']}** result(s): {notable} hardening/configuration finding(s) "
               f"and {s.get('Informational', 0)} informational observation(s). No exploitation was attempted. "
               "Severity reflects demonstrated impact and context; a missing header alone is never rated High.")
    out += ["", "## Target and Scan Details", "", "| Item | Value |", "|---|---|",
            f"| Target | {_cell(r['target'])} |", f"| Requests made | {r['summary']['requests_made']} |",
            f"| Duration | {r['summary']['duration_seconds']} s |",
            f"| Checks run | {_cell(', '.join(k for k, v in r['scan_configuration'].get('checks', {}).items() if v))} |",
            "", "## Scope Statement", "", r["scope_statement"], "", "## Summary of Findings", "",
            "| Severity | Count |", "|---|---|"]
    out += [f"| {sev} | {s.get(sev, 0)} |" for sev in ORDER]
    if r["scan_errors"]:
        out += ["", "### Scan notes", ""] + [f"- {e}" for e in r["scan_errors"]]
    out += ["", "| ID | Title | Severity | Confidence | Type | Validation |", "|---|---|---|---|---|---|"]
    for f in r["findings"]:
        out.append(f"| {f['finding_id']} | {_cell(f['title'])} | {f['severity']} | {f['confidence']} | "
                   f"{_cell(f['classification'])} | {f['validation_status']} |")
    out += ["", "## Findings", ""]
    if not r["findings"]:
        out += ["No findings were recorded.", ""]
    for f in r["findings"]:
        cwe = f["cwe"] or f"None ({f['cwe_note']})"
        out += [f"### {f['finding_id']} - {f['title']}", "",
                f"- **Severity:** {f['severity']}  |  **Confidence:** {f['confidence']}  |  **Type:** {f['classification']}",
                f"- **Validation status:** {f['validation_status']}", f"- **CWE:** {cwe}",
                f"- **Category / check:** {f['category']} / {f['check_type']}",
                f"- **Target:** {f['target']}  |  **Observed at:** {f['timestamp']}", "",
                f"**Why it was identified:** {f['description']}", "",
                f"**Observation:** {f['observation']}", "", "**Evidence:**", "", "```"]
        out += [f"{k}: {v}" for k, v in f["evidence"].items()]
        out += ["```", "", f"**Expected behavior:** {f['expected']}", "",
                f"**What the evidence proves:** {f['proves']}", "",
                f"**What it does not prove:** {f['not_proves']}", "",
                f"**Potential impact:** {f['impact']}", "",
                f"**Confidence rationale:** {f['confidence_reason']}", "",
                f"**False-positive considerations:** {f['false_positive_notes']}", "",
                f"**Remediation:** {f['remediation']}", "",
                f"**Manual verification:** {f['manual_verification']}", ""]
        if f.get("user_note"):
            out += [f"**Reviewer note:** {f['user_note']}", ""]
    out += ["## Limitations", ""] + [f"- {l}" for l in r["limitations"]]
    out += ["", "## Disclaimer", "", r["disclaimer"], ""]
    return "\n".join(out)


def export_markdown(scan: dict, path: str | Path) -> Path:
    path = Path(path)
    try:
        path.write_text(to_markdown(scan), encoding="utf-8")
    except PermissionError:
        raise ExportError(f"Permission denied writing to {path}. Choose a folder you can write to.") from None
    except OSError as exc:
        raise ExportError(f"The report could not be saved: {exc.strerror or exc}") from None
    return path
